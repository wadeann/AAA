# ── 最终股票列表（去重） ──
STOCK_UNIVERSE: List[str] = sorted(set(STOCK_INDUSTRY.keys()))


def get_industry(symbol: str) -> str:
    """返回股票所属行业，未知返回'未知'."""
    return STOCK_INDUSTRY.get(symbol, "未知")


def get_universe_size() -> int:
    return len(STOCK_UNIVERSE)


def get_industry_distribution() -> Dict[str, int]:
    dist: Dict[str, int] = {}
    for sym in STOCK_UNIVERSE:
        ind = get_industry(sym)
        dist[ind] = dist.get(ind, 0) + 1
    return dist


